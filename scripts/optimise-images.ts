/**
 * Optimises the 2x PNG exports from Figma for the web.
 *
 * Input:  assets/images/**\/*.png   (exported from the "Export · Website images" page, not committed)
 * Output: public/images/**          AVIF, WebP and JPEG at several widths
 *         content/image-manifest.ts list of available images and their sizes
 *
 * Images that are missing from the manifest render as a neutral placeholder,
 * so the site builds before any images exist.
 */
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import sharp from 'sharp';

const root = resolve(import.meta.dirname, '..');
const inputDir = join(root, 'assets/images');
const outputDir = join(root, 'public/images');

/** Smallest width generated, so phones never download the full 2x file. */
const MIN_WIDTH = 640;

const findPngs = (dir: string): string[] =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return findPngs(path);
    return name.toLowerCase().endsWith('.png') ? [path] : [];
  });

const widthsFor = (width: number) =>
  [...new Set([MIN_WIDTH, Math.round(width / 2), width])]
    .filter((w) => w <= width)
    .sort((a, b) => a - b);

let files: string[] = [];
try {
  files = findPngs(inputDir);
} catch {
  console.log('No assets/images folder yet. Export the images from Figma first (see README).');
}

const manifest: Record<string, { width: number; height: number; widths: number[] }> = {};

for (const file of files) {
  // "rivo/01-hero@2x.png" and "rivo/01-hero.png" both become "rivo/01-hero"
  const key = relative(inputDir, file)
    .replace(/\\/g, '/')
    .replace(/(@2x)?\.png$/i, '');
  const image = sharp(file);
  const { width = 0, height = 0 } = await image.metadata();
  const widths = widthsFor(width);
  mkdirSync(dirname(join(outputDir, key)), { recursive: true });

  for (const w of widths) {
    const base = join(outputDir, `${key}-${w}`);
    const resized = image.clone().resize({ width: w });
    await Promise.all([
      resized.clone().avif({ quality: 60 }).toFile(`${base}.avif`),
      resized.clone().webp({ quality: 80 }).toFile(`${base}.webp`),
      resized
        .clone()
        .flatten({ background: '#ffffff' })
        .jpeg({ quality: 82, mozjpeg: true })
        .toFile(`${base}.jpg`),
    ]);
  }

  manifest[key] = { width, height, widths };
  console.log(`${key}  ${width}×${height}  → ${widths.join(', ')}`);
}

const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  join(root, 'content/image-manifest.ts'),
  `// Generated by scripts/optimise-images.ts. Do not edit by hand.\n\nexport const imageManifest: Record<string, { width: number; height: number; widths: number[] }> = ${JSON.stringify(sorted, null, 2)};\n`,
);
console.log(`\n${files.length} images written to public/images`);
