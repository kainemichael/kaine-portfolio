/**
 * Turns tokens/figma-variables.json into styles/tokens.css.
 *
 * Naming follows the Figma README: the collection is dropped and slashes
 * become dashes, so Theme "bg/page" becomes --bg-page.
 * Theme switches with [data-theme="dark"]; Layout switches at 767px.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

type Value = string | number;
type Collection = { modes: string[]; variables: Record<string, Record<string, Value>> };
type Shadow = {
  inset?: boolean;
  x: number;
  y: number;
  blur: number;
  spread: number;
  color: string;
};
type Source = {
  collections: Record<'Primitives' | 'Theme' | 'Layout', Collection>;
  textStyles: Record<
    string,
    { family: 'sans' | 'mono'; weight: number; tracking: number; size: string }
  >;
  effectStyles: Record<string, { blur?: number; shadows: Shadow[] }>;
};

const MOBILE_QUERY = '(max-width: 767px)';

const root = resolve(import.meta.dirname, '..');
const source: Source = JSON.parse(
  readFileSync(resolve(root, 'tokens/figma-variables.json'), 'utf8'),
);

const toProp = (name: string) => `--${name.replace(/\//g, '-').replace(/\s+/g, '-').toLowerCase()}`;

const toValue = (value: Value) => {
  if (typeof value === 'number') return value === 0 ? '0' : `${value}px`;
  const alias = value.match(/^\{(.+)\}$/)?.[1];
  return alias ? `var(${toProp(alias)})` : value;
};

const block = (selector: string, lines: string[], indent = '') =>
  [`${indent}${selector} {`, ...lines.map((l) => (l ? `${indent}  ${l}` : '')), `${indent}}`].join(
    '\n',
  );

const declarations = (collection: Collection, mode: string) =>
  Object.entries(collection.variables).map(([name, modes]) => {
    const value = modes[mode];
    if (value === undefined) throw new Error(`${name} has no value for mode "${mode}"`);
    return `${toProp(name)}: ${toValue(value)};`;
  });

const { Primitives, Theme, Layout } = source.collections;

const typeLines = Object.values(source.textStyles).flatMap((style) => {
  const prop = toProp(style.size);
  const family = style.family === 'mono' ? 'var(--font-mono)' : 'var(--font-sans)';
  return [
    `${prop}: ${style.weight} var(${toProp(`${style.size}/size`)}) / var(${toProp(`${style.size}/line-height`)}) ${family};`,
    `${prop}-tracking: ${style.tracking === 0 ? 'normal' : `${style.tracking / 100}em`};`,
  ];
});

const shadow = (s: Shadow) =>
  `${s.inset ? 'inset ' : ''}${s.x}px ${s.y}px ${s.blur}px ${s.spread}px ${s.color}`;
const effectLines = Object.entries(source.effectStyles).flatMap(([name, effect]) => {
  const prop = toProp(name);
  const lines = [`${prop}: ${effect.shadows.map(shadow).join(', ')};`];
  if (effect.blur) lines.push(`${prop}-blur: ${effect.blur}px;`);
  return lines;
});

const css = [
  '/* Generated by scripts/build-tokens.ts from tokens/figma-variables.json. Do not edit by hand. */',
  '',
  block(':root', [
    '/* Fonts (loaded by next/font in app/layout.tsx) */',
    '--font-sans: var(--font-geist-sans), system-ui, sans-serif;',
    '--font-mono: var(--font-geist-mono), ui-monospace, monospace;',
    '',
    '/* Primitives: feed Theme only, never use in components */',
    ...declarations(Primitives, 'Value'),
    '',
    '/* Theme · Light */',
    ...declarations(Theme, 'Light'),
    '',
    '/* Layout · Desktop */',
    ...declarations(Layout, 'Desktop'),
    '',
    '/* Text styles: `font: var(--type-body)` plus `letter-spacing: var(--type-body-tracking)` */',
    ...typeLines,
    '',
    '/* Effect styles */',
    ...effectLines,
  ]),
  '',
  block('[data-theme="dark"]', ['color-scheme: dark;', ...declarations(Theme, 'Dark')]),
  '',
  `@media ${MOBILE_QUERY} {`,
  block(':root', declarations(Layout, 'Mobile'), '  '),
  '}',
  '',
].join('\n');

writeFileSync(resolve(root, 'styles/tokens.css'), css);
console.log('styles/tokens.css written');
